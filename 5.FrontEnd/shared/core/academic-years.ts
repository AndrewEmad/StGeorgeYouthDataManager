export function canonicalAcademicYear(value:string|null|undefined):string|null {
 if(!value?.trim())return '';
 let key=value.toLowerCase().replace(/[\s\u200e\u200f\u061c\u200b\u064b-\u065f\u0670\u0640]/g,'').replace(/[أإآٱ]/g,'ا').replace(/[ىی]/g,'ي').replace(/ة/g,'ه');
 key=key.replace(/\((?:هيتخرج|سيتخرج|هتتخرج|ستتخرج).*$/,'');
 for(const prefix of ["السنهالدراسيه", "سنهدراسيه", "العامالدراسي", "السنه", "سنه", "الفرقه", "فرقه"])if(key.startsWith(prefix)){key=key.slice(prefix.length);break;}
 for(const suffix of ["بالجامعه", "جامعيه", "جامعي", "جامعه"])if(key.endsWith(suffix)){key=key.slice(0,-suffix.length);break;}
 if(Object.prototype.hasOwnProperty.call(academicYearAliases,key))return academicYearAliases[key];
 for(const prefix of ["خريج","الخريج","اتخرجت","تخرجت","متخرج","المتخرج"])if(key.startsWith(prefix))return "حديث التخرج";
 return null;
}

